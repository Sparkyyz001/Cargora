/** Детерминированный список инцидентов за последние сутки. */
export function getIncidents(): Incident[] {
  return TEMPLATES.map((t, i) => ({
    ...t,
    id: i + 1,
    // Раскидываем по последним 26 часам с постоянным шагом
    hoursAgo: Math.round((i * 3.2 + 1.5) * 10) / 10,
    // Старые инциденты считаем закрытыми
    resolved: i >= 4,
  }))
}
